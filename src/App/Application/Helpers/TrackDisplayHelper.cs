    /// <summary>
    /// Convert an ISO 639 language code to a user-friendly display name.
    /// Falls back to the original code if unknown.
    /// </summary>
    public static string GetLanguageName(string? code)
    {
        if (string.IsNullOrWhiteSpace(code)) return "Unknown";
        var key = code.ToLowerInvariant().Trim();
        // Handle "AG-en" style codes from external subtitle filenames
        if (key.Contains('-'))
        {
            var parts = key.Split('-');
            var last = parts[^1];
            if (LanguageNames.TryGetValue(last, out var name))
                return name;
        }
        return LanguageNames.TryGetValue(key, out var n) ? n : code;
    }

    /// <summary>
    /// Format a subtitle/audio/video track entry for display.
    /// Subtitle tracks show language + tags (External, Forced, SDH, PGS).
    /// Audio/video tracks use a "Language (type)" format.
    /// </summary>
    public static string FormatTrack(TrackType type, SubtitleSource track)
    {
        var lang = GetLanguageName(track.Language);

        if (type == TrackType.Subtitle)
        {
            var tags = new List<string>();
            if (track.IsExternal) tags.Add("External");
            if (track.IsForced) tags.Add("Forced");
            if (track.IsHearingImpaired) tags.Add("SDH");
            if (track.IsBitmap) tags.Add("PGS");
            return tags.Count > 0
                ? $"{lang} ({string.Join(", ", tags)})"
                : lang;
        }

        // Audio/video — append type prefix
        var typeLabel = type == TrackType.Audio ? "Audio" : "Video";
        return $"{lang} ({typeLabel})";
    }
